#[repr(C)]
pub enum mbedtls_md_type_t {
    MBEDTLS_MD_NONE = 0,
    MBEDTLS_MD_MD2,
    MBEDTLS_MD_MD4,
    MBEDTLS_MD_MD5,
    MBEDTLS_MD_SHA1,
    MBEDTLS_MD_SHA224,
    MBEDTLS_MD_SHA256,
    MBEDTLS_MD_SHA384,
    MBEDTLS_MD_SHA512,
    MBEDTLS_MD_RIPEMD160,
}

pub fn mbedtls_ssl_get_ciphersuite_sig_pk_alg(info: &mbedtls_ssl_ciphersuite_t) -> mbedtls_pk_type_t {
    match info.key_exchange {
        mbedtls_key_exchange_type_t::MBEDTLS_KEY_EXCHANGE_RSA |
        mbedtls_key_exchange_type_t::MBEDTLS_KEY_EXCHANGE_DHE_RSA |
        mbedtls_key_exchange_type_t::MBEDTLS_KEY_EXCHANGE_ECDHE_RSA |
        mbedtls_key_exchange_type_t::MBEDTLS_KEY_EXCHANGE_RSA_PSK => mbedtls_pk_type_t::MBEDTLS_PK_RSA,
        mbedtls_key_exchange_type_t::MBEDTLS_KEY_EXCHANGE_ECDHE_ECDSA => mbedtls_pk_type_t::MBEDTLS_PK_ECDSA,
        mbedtls_key_exchange_type_t::MBEDTLS_KEY_EXCHANGE_ECDH_RSA |
        mbedtls_key_exchange_type_t::MBEDTLS_KEY_EXCHANGE_ECDH_ECDSA => mbedtls_pk_type_t::MBEDTLS_PK_ECKEY,
        _ => mbedtls_pk_type_t::MBEDTLS_PK_NONE,
    }
}
