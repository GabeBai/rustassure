#[repr(C)]
pub enum MbedtlsKeyExchangeType {
    None = 0,
    Rsa,
    DheRsa,
    EcdheRsa,
    EcdheEcdsa,
    Psk,
    DhePsk,
    RsaPsk,
    EcdhePsk,
    EcdhRsa,
    EcdhEcdsa,
    Ecjpake,
}

#[repr(C)]
pub struct MbedtlsSslCiphersuite {
    pub id: i32,
    pub name: *const i8,
    pub cipher: MbedtlsCipherType,
    pub mac: MbedtlsMdType,
    pub key_exchange: MbedtlsKeyExchangeType,
    pub min_major_ver: i32,
    pub min_minor_ver: i32,
    pub max_major_ver: i32,
    pub max_minor_ver: i32,
    pub flags: u8,
}

pub fn mbedtls_ssl_ciphersuite_uses_server_signature(info: &MbedtlsSslCiphersuite) -> i32 {
    match info.key_exchange {
        MbedtlsKeyExchangeType::DheRsa | MbedtlsKeyExchangeType::EcdheRsa | MbedtlsKeyExchangeType::EcdheEcdsa => 1,
        _ => 0,
    }
}
