pub fn mbedtls_ssl_get_ciphersuite_sig_alg(info: &MbedtlsSslCiphersuite) -> MbedtlsPkType {
    match info.key_exchange {
        MbedtlsKeyExchangeType::MbedtlsKeyExchangeRsa |
        MbedtlsKeyExchangeType::MbedtlsKeyExchangeDheRsa |
        MbedtlsKeyExchangeType::MbedtlsKeyExchangeEcdheRsa => MbedtlsPkType::MbedtlsPkRsa,
        MbedtlsKeyExchangeType::MbedtlsKeyExchangeEcdheEcdsa => MbedtlsPkType::MbedtlsPkEcdsa,
        _ => MbedtlsPkType::MbedtlsPkNone,
    }
}
