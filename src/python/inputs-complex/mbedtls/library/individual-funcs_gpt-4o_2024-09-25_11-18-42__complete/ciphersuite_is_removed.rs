struct MbedtlsSslCiphersuite {
    id: i32,
    name: &'static str,
    cipher: MbedtlsCipherType,
    mac: i32,
    key_exchange: i32,
    min_major_ver: i32,
    min_minor_ver: i32,
    max_major_ver: i32,
    max_minor_ver: i32,
    flags: u8,
}

fn ciphersuite_is_removed(cs_info: &MbedtlsSslCiphersuite) -> i32 {
    if cs_info.cipher == MbedtlsCipherType::MBEDTLS_CIPHER_ARC4_128 {
        return 1;
    }
    if cs_info.cipher == MbedtlsCipherType::MBEDTLS_CIPHER_DES_EDE3_ECB
        || cs_info.cipher == MbedtlsCipherType::MBEDTLS_CIPHER_DES_EDE3_CBC
    {
        return 1;
    }
    0
}

fn main() {
    // Example usage
    let cs_info = MbedtlsSslCiphersuite {
        id: 0,
        name: "example",
        cipher: MbedtlsCipherType::MBEDTLS_CIPHER_ARC4_128,
        mac: 0,
        key_exchange: 0,
        min_major_ver: 0,
        min_minor_ver: 0,
        max_major_ver: 0,
        max_minor_ver: 0,
        flags: 0,
    };

    let result = ciphersuite_is_removed(&cs_info);
    println!("Is ciphersuite removed? {}", result);
}
