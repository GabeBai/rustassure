fn scan_part(start: &str, category: Category, delimiter1: char, delimiter2: char) -> Option<&str> {
    let mut p = start;
    loop {
        if p.is_empty() || p.chars().next() == Some(delimiter1) || p.chars().next() == Some(delimiter2) {
            return Some(p);
        }
        if CHAR_CAT[p.chars().next().unwrap() as usize] & category as u16 != 0 {
            p = &p[p.chars().next().unwrap().len_utf8()..];
        } else {
            return None;
        }
    }
}

fn main() {
    let input = "example_input";
    let category = Category::Scheme;
    let delimiter1 = '/';
    let delimiter2 = '?';

    if let Some(result) = scan_part(input, category, delimiter1, delimiter2) {
        println!("Result: {}", result);
    } else {
        println!("No valid result found.");
    }
}
